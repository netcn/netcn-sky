/* 用经纬度找最近城市（定位失败时用 IP 估计也可复用） */
export function nearestCity(lat, lon) {
  let best = null, bestD = Infinity;
  for (const c of CITIES) {
    const d = (c.lat - lat) ** 2 + ((c.lon - lon) * Math.cos((lat * Math.PI) / 180)) ** 2;
    if (d < bestD) { bestD = d; best = c; }
  }
  return best;
}

